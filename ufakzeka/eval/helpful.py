"""Helpfulness eval: multi turn conversations scored by a judge model on task completion and coherence.

The behaviour eval (ufakzeka.eval.behavior) only checks refusal, abstention, identity, facts and arithmetic with
regexes, so a model can score 100 there while deflecting every real request. This eval runs 40 scripted
conversations (the user turns are fixed, the assistant turns are generated by the model given its own earlier
answers) and asks an LLM judge to score each assistant turn:
  task 0-2   did the turn do what was asked (story told, advice given, list given, correction followed)
  coherent 0-2   consistent with the conversation so far, no topic drift, no recycled earlier words
  deflect 0-1   1 if the turn hands the work back to the user (a question instead of content) or abstains needlessly
Reported: mean task, mean coherent, deflection rate, and an overall 0-100 score.

  python -m ufakzeka.eval.helpful --model models/ufakzeka-1-instruct-v7/hf --out evals/helpful_v7.json
Costs a few cents of LLM API calls (key in ~/.ufakzeka/llm_api_key)."""

